/**
 * Exports the LIVE database definition (and optionally its data) as plain SQL files:
 *   npm run db:export-schema            -> ../database/schema/smart_campus_schema.sql
 *   npm run db:export-schema -- --data  -> also ../database/seeds/smart_campus_seed_data.sql
 * Uses SHOW CREATE ... so it needs no mysqldump binary (handy on Windows).
 */
import fs from 'node:fs';
import path from 'node:path';
import mysql from 'mysql2/promise';
import { query, closePool } from './mysql';

const OUT_SCHEMA = path.resolve(__dirname, '../../../database/schema/smart_campus_schema.sql');
const OUT_DATA = path.resolve(__dirname, '../../../database/seeds/smart_campus_seed_data.sql');
const strip = (s: string) => s.replace(/\sDEFINER=`[^`]+`@`[^`]+`/g, '').replace(/ALGORITHM=\w+\s/g, '').replace(/SQL SECURITY \w+\s/g, '');
const first = (r: Record<string, unknown>, key: string) => String(r[key]);

async function main() {
  const withData = process.argv.includes('--data');
  const db = (await query<{ d: string }>('SELECT DATABASE() AS d'))[0].d;
  const out: string[] = [`-- QuadBook schema export (${db})`, '-- Generated by backend/src/db/exportSchema.ts. Source of truth: database/migrations/*.sql', 'SET FOREIGN_KEY_CHECKS = 0;', ''];

  const tables = (await query<Record<string, unknown>>("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'")).map((r) => String(Object.values(r)[0]));
  for (const t of tables) { const r = (await query<Record<string, unknown>>(`SHOW CREATE TABLE \`${t}\``))[0]; out.push(`DROP TABLE IF EXISTS \`${t}\`;`, `${first(r, 'Create Table')};`, ''); }

  out.push('DELIMITER $$');
  for (const kind of ['FUNCTION', 'PROCEDURE'] as const) {
    const rows = await query<Record<string, unknown>>(`SHOW ${kind} STATUS WHERE Db = ?`, [db]);
    for (const r of rows) {
      const name = String(r.Name); const c = (await query<Record<string, unknown>>(`SHOW CREATE ${kind} \`${name}\``))[0];
      out.push(`DROP ${kind} IF EXISTS \`${name}\`$$`, `${strip(first(c, `Create ${kind === 'FUNCTION' ? 'Function' : 'Procedure'}`))}$$`, '');
    }
  }
  // views call the functions above, so they come after them
  out.push('DELIMITER ;', '');
  const views = (await query<Record<string, unknown>>("SHOW FULL TABLES WHERE Table_type = 'VIEW'")).map((r) => String(Object.values(r)[0]));
  for (const v of views) { const r = (await query<Record<string, unknown>>(`SHOW CREATE VIEW \`${v}\``))[0]; out.push(`DROP VIEW IF EXISTS \`${v}\`;`, `${strip(first(r, 'Create View'))};`, ''); }
  out.push('DELIMITER $$');
  const triggers = await query<Record<string, unknown>>('SHOW TRIGGERS');
  for (const t of triggers) {
    const name = String(t.Trigger); const c = (await query<Record<string, unknown>>(`SHOW CREATE TRIGGER \`${name}\``))[0];
    out.push(`DROP TRIGGER IF EXISTS \`${name}\`$$`, `${strip(first(c, 'SQL Original Statement'))}$$`, '');
  }
  out.push('DELIMITER ;', '', 'SET FOREIGN_KEY_CHECKS = 1;', '');
  fs.mkdirSync(path.dirname(OUT_SCHEMA), { recursive: true });
  fs.writeFileSync(OUT_SCHEMA, out.join('\n'));
  console.log(`Schema: ${tables.length} tables, ${views.length} views, ${triggers.length} triggers -> ${OUT_SCHEMA}`);

  if (withData) {
    const data: string[] = [`-- QuadBook seed data (${db}). Load AFTER the schema:  mysql -u <user> -p ${db} < smart_campus_seed_data.sql`, 'SET FOREIGN_KEY_CHECKS = 0;', 'SET @sc_seeding = 1;', ''];
    let total = 0;
    const skip = new Set(['revoked_tokens', 'password_reset_tokens']);
    // parents before children, so the booking trigger can see its resource while seed rows load
    const order = ['roles', 'departments', 'buildings', 'rooms', 'resource_categories', 'users', 'resources', 'equipment', 'academic_schedules', 'maintenance_requests', 'bookings', 'booking_equipment', 'booking_approvals', 'booking_status_history', 'notifications', 'system_settings'];
    for (const t of [...order, ...tables.filter((x) => !order.includes(x))].filter((x) => tables.includes(x) && !skip.has(x))) {
      const rows = await query<Record<string, unknown>>(`SELECT * FROM \`${t}\``);
      if (!rows.length) continue;
      const cols = Object.keys(rows[0]).map((c) => `\`${c}\``).join(', ');
      data.push(`-- ${t} (${rows.length} rows)`, `DELETE FROM \`${t}\`;`);
      for (let i = 0; i < rows.length; i += 200) {
        const chunk = rows.slice(i, i + 200).map((r) => `(${Object.values(r).map((v) => mysql.escape(v as never)).join(', ')})`);
        data.push(`INSERT INTO \`${t}\` (${cols}) VALUES\n${chunk.join(',\n')};`);
      }
      data.push(''); total += rows.length;
    }
    data.push('SET FOREIGN_KEY_CHECKS = 1;', '');
    fs.mkdirSync(path.dirname(OUT_DATA), { recursive: true });
    fs.writeFileSync(OUT_DATA, data.join('\n'));
    console.log(`Data: ${total} rows -> ${OUT_DATA}`);
  }
  await closePool();
}
main().catch((e) => { console.error(e); process.exit(1); });
